# ---------------------------------------------------------------------------
# Hybrid-aware evaluation: re-run evaluate_strategy using hybrid retrieval
# ---------------------------------------------------------------------------

def evaluate_with_mode(collection, questions, k, mode="semantic"):
    """Run evaluate_strategy but with a specific search mode.

    For 'semantic' this is identical to the existing evaluate_strategy.
    For 'hybrid' or 'bm25', we monkey-patch the query function temporarily.
    """
    if mode == "semantic":
        return evaluate_strategy(collection, questions, k=k)

    # For non-semantic modes, we need to swap the query function used by
    # evaluate_question. Rather than modifying evaluate.py, we build the
    # results manually using the same logic.
    from evaluate import judge
    from retrieve import collection_for

    strategy = None
    for s, coll_name in STRATEGIES.items():
        if coll_name == collection.name:
            strategy = s
            break

    if strategy is None:
        strategy = "structured"

    from retrieve import search as retrieve_search

    per_q = []
    for q in questions:
        hits = retrieve_search(q["question"], strategy=strategy, k=k, mode=mode)
        first_hit = None
        first_answer = None
        rows = []
        for h in hits:
            recipe_ok, section_ok, marker_ok = judge(h, q)
            if recipe_ok and section_ok and first_hit is None:
                first_hit = h["rank"]
            if recipe_ok and marker_ok and first_answer is None:
                first_answer = h["rank"]
            rows.append({
                "rank": h["rank"],
                "chunk_id": h["chunk_id"],
                "recipe_id": (h["metadata"] or {}).get("recipe_id", ""),
                "section": (h["metadata"] or {}).get("section", ""),
                "score": h["score"],
                "distance": h["distance"],
                "correct": bool(recipe_ok and section_ok),
                "has_answer": bool(recipe_ok and marker_ok),
                "snippet": " ".join(h["text"].split())[:150],
            })
        per_q.append({
            "qid": q["qid"],
            "question": q["question"],
            "type": q["type"],
            "gold_recipes": q["gold_recipes"],
            "gold_section": q["gold_section"],
            "expected_answer": q["answer"],
            "first_hit_rank": first_hit,
            "first_answer_rank": first_answer,
            "hit": first_hit is not None,
            "answer_present": first_answer is not None,
            "results": rows,
        })

    return {
        "k": k,
        "hits": sum(1 for r in per_q if r["hit"]),
        "answers": sum(1 for r in per_q if r["answer_present"]),
        "total": len(per_q),
        "per_question": per_q,
    }


